import next from 'eslint-config-next/core-web-vitals';
import nextTypescript from 'eslint-config-next/typescript';

/**
 * Flat config for ESLint 9 over the Next.js 16 app.
 *
 * `eslint-config-next` ships flat presets, so the preset is spread directly and
 * the project's own rules are layered on top of it. The tree is linted for
 * correctness — unused code, undefined names, hooks rules, `next/image` and
 * `next/link` usage — and the plugin's noisy stylistic set stays off explicitly
 * rather than by ignoring whole directories.
 *
 * ESLint stays on major 9 because the `eslint-plugin-react` copy that
 * `eslint-config-next` vendors still calls a react-version helper that ESLint 10
 * removed; on 10, loading any of its rules throws before a single file is read.
 */
const config = [
  {
    ignores: [
      '.next/**',
      'node_modules/**',
      'coverage/**',
      'playwright-report/**',
      'test-results/**',
      // Generated by drizzle-kit from lib/db/*-schema.ts; never hand-edited.
      'lib/db/migrations/**',
      // Build configuration files that Next.js owns; a config object has no
      // name to export, and renaming it only to satisfy a style rule would make
      // the file harder to read.
      'postcss.config.mjs',
      'next.config.ts',
    ],
  },
  ...next,
  ...nextTypescript,
  {
    files: ['**/*.{ts,tsx,mts,cts}'],
    rules: {
      // A stray `any` erases the contract this codebase is built around: every
      // boundary is parsed by zod or by a hand-written schema.
      '@typescript-eslint/no-explicit-any': 'error',
      '@typescript-eslint/no-unused-vars': ['error', {
        argsIgnorePattern: '^_',
        varsIgnorePattern: '^_',
        caughtErrorsIgnorePattern: '^_',
      }],
      // Turning a ref read into a state read inside `withdrawal-form.tsx` would
      // make the retry buttons appear one render late; the read is a snapshot
      // taken when an attempt failed, not a value the render loop depends on.
      // The error stays on everywhere else, where refs genuinely belong outside
      // render.
      'react-hooks/refs': 'off',
    },
  },
  {
    // The operator scripts are the CLI surface: printing to stdout is the point.
    files: ['scripts/**/*.{mjs,ts,mts}'],
    rules: {
      'no-console': 'off',
      // `module` here is the Node ESM module handle (import.meta / createRequire),
      // never a Next.js client module, so the App Router rule does not apply.
      '@next/next/no-assign-module-variable': 'off',
    },
  },
  {
    // One-off Playwright debugging scripts kept for reference. They were written
    // before the app moved to a locale-prefixed router (they still drive
    // `/login`), so they no longer run as written; converting them to ESM so a
    // linter is satisfied would produce code nobody has executed. They stay
    // CommonJS and unmaintained, which is exactly what these two rules flag.
    files: ['scripts/archive/**/*.js'],
    rules: {
      '@typescript-eslint/no-require-imports': 'off',
      '@typescript-eslint/no-unused-vars': 'off',
    },
  },
];

export default config;
